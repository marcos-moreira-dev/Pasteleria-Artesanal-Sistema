CREATE TABLE IF NOT EXISTS core.organizacion_empresa (
    empresa_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(40) NOT NULL UNIQUE,
    nombre_comercial VARCHAR(160) NOT NULL,
    razon_social VARCHAR(160),
    moneda_base VARCHAR(3) NOT NULL DEFAULT 'USD',
    activa BOOLEAN NOT NULL DEFAULT TRUE,
    creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    actualizado_en TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS core.sucursal_operativa (
    sucursal_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id BIGINT NOT NULL REFERENCES core.organizacion_empresa(empresa_id),
    codigo VARCHAR(40) NOT NULL,
    nombre VARCHAR(160) NOT NULL,
    principal BOOLEAN NOT NULL DEFAULT FALSE,
    activa BOOLEAN NOT NULL DEFAULT TRUE,
    creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    actualizado_en TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_sucursal_operativa_codigo UNIQUE (empresa_id, codigo)
);

CREATE TABLE IF NOT EXISTS seguridad.permiso_operacion (
    permiso_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(80) NOT NULL UNIQUE,
    modulo VARCHAR(80) NOT NULL,
    descripcion TEXT NOT NULL,
    alcance VARCHAR(20) NOT NULL CHECK (alcance IN ('GLOBAL','SUCURSAL')),
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS seguridad.rol_operacion (
    rol_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(80) NOT NULL UNIQUE,
    nombre VARCHAR(120) NOT NULL,
    descripcion TEXT,
    alcance VARCHAR(20) NOT NULL CHECK (alcance IN ('GLOBAL','SUCURSAL')),
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS seguridad.rol_permiso (
    rol_id BIGINT NOT NULL REFERENCES seguridad.rol_operacion(rol_id) ON DELETE CASCADE,
    permiso_id BIGINT NOT NULL REFERENCES seguridad.permiso_operacion(permiso_id) ON DELETE CASCADE,
    creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    PRIMARY KEY (rol_id, permiso_id)
);

CREATE TABLE IF NOT EXISTS seguridad.usuario_rol_global_mapeo (
    usuario_id BIGINT NOT NULL,
    rol_id BIGINT NOT NULL REFERENCES seguridad.rol_operacion(rol_id),
    creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    PRIMARY KEY (usuario_id, rol_id)
);

CREATE TABLE IF NOT EXISTS seguridad.usuario_sucursal_mapeo (
    usuario_id BIGINT NOT NULL,
    sucursal_id BIGINT NOT NULL REFERENCES core.sucursal_operativa(sucursal_id),
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    PRIMARY KEY (usuario_id, sucursal_id)
);

CREATE TABLE IF NOT EXISTS seguridad.usuario_sucursal_rol_mapeo (
    usuario_id BIGINT NOT NULL,
    sucursal_id BIGINT NOT NULL REFERENCES core.sucursal_operativa(sucursal_id),
    rol_id BIGINT NOT NULL REFERENCES seguridad.rol_operacion(rol_id),
    creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    PRIMARY KEY (usuario_id, sucursal_id, rol_id)
);

