CREATE TABLE IF NOT EXISTS tesoreria.caja_operativa (
    caja_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sucursal_id BIGINT REFERENCES core.sucursal_operativa(sucursal_id),
    codigo VARCHAR(40) NOT NULL UNIQUE,
    nombre VARCHAR(120) NOT NULL,
    tipo_caja VARCHAR(30) NOT NULL DEFAULT 'VENTA' CHECK (tipo_caja IN ('VENTA','CAJA_CHICA','EVENTO','DELIVERY','OTRA')),
    moneda VARCHAR(3) NOT NULL DEFAULT 'USD',
    saldo_actual NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (saldo_actual >= 0),
    activa BOOLEAN NOT NULL DEFAULT TRUE,
    creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    actualizado_en TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS tesoreria.turno_caja (
    turno_caja_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    caja_id BIGINT NOT NULL REFERENCES tesoreria.caja_operativa(caja_id),
    usuario_apertura_id BIGINT NOT NULL,
    usuario_cierre_id BIGINT,
    fecha_apertura TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    fecha_cierre TIMESTAMPTZ,
    monto_apertura NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (monto_apertura >= 0),
    monto_cierre_sistema NUMERIC(12,2),
    monto_cierre_declarado NUMERIC(12,2),
    diferencia_cierre NUMERIC(12,2),
    estado VARCHAR(20) NOT NULL CHECK (estado IN ('ABIERTO','CERRADO','ANULADO')),
    observaciones_apertura VARCHAR(500),
    observaciones_cierre VARCHAR(500),
    creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    actualizado_en TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE UNIQUE INDEX IF NOT EXISTS ux_tesoreria_turno_caja_unico_abierto
    ON tesoreria.turno_caja (caja_id)
    WHERE estado = 'ABIERTO';

CREATE TABLE IF NOT EXISTS tesoreria.movimiento_caja (
    movimiento_caja_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    turno_caja_id BIGINT NOT NULL REFERENCES tesoreria.turno_caja(turno_caja_id),
    tipo_movimiento VARCHAR(40) NOT NULL,
    naturaleza VARCHAR(20) NOT NULL CHECK (naturaleza IN ('ENTRADA','SALIDA','AJUSTE')),
    fecha_movimiento TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    monto NUMERIC(12,2) NOT NULL CHECK (monto > 0),
    moneda VARCHAR(3) NOT NULL DEFAULT 'USD',
    referencia_tipo VARCHAR(80),
    referencia_id VARCHAR(120),
    descripcion VARCHAR(500),
    estado VARCHAR(20) NOT NULL DEFAULT 'REGISTRADO' CHECK (estado IN ('REGISTRADO','ANULADO')),
    creado_por_usuario_id BIGINT NOT NULL,
    anulado_por_usuario_id BIGINT,
    anulado_en TIMESTAMPTZ,
    motivo_anulacion VARCHAR(500)
);

CREATE TABLE IF NOT EXISTS tesoreria.arqueo_caja (
    arqueo_caja_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    turno_caja_id BIGINT NOT NULL REFERENCES tesoreria.turno_caja(turno_caja_id),
    fecha_arqueo TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    monto_sistema NUMERIC(12,2) NOT NULL CHECK (monto_sistema >= 0),
    monto_declarado NUMERIC(12,2) NOT NULL CHECK (monto_declarado >= 0),
    diferencia NUMERIC(12,2) NOT NULL,
    estado VARCHAR(20) NOT NULL DEFAULT 'CONFIRMADO' CHECK (estado IN ('BORRADOR','CONFIRMADO','APROBADO','ANULADO')),
    observaciones VARCHAR(500),
    creado_por_usuario_id BIGINT NOT NULL
);

