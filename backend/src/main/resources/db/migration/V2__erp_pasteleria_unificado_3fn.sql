-- =============================================================================
-- PASTELERIA ERP - V2 ERP TRANSICIONAL EN 3FN (SCAFFOLDING CONTROLADO)
-- Tanda: T07 - Base de datos V1/V2 y migraciones por ambiente
--
-- Esta migración NO borra tablas V1 ni intenta terminar todo el ERP en una sola
-- pasada. Crea los schemas objetivo y las tablas mínimas de control para poder
-- migrar por fases sin romper backend/admin/storefront.
--
-- La V2 completa se irá expandiendo en las tandas T09..T21 antes de producción
-- real. Mientras no exista despliegue productivo, esta V2 puede seguirse
-- refinando como baseline ERP.
-- =============================================================================

