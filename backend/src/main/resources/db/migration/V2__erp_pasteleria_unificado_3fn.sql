CREATE TABLE IF NOT EXISTS core.erp_migration_marker (
    marker_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(80) NOT NULL UNIQUE,
    descripcion TEXT NOT NULL,
    creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

COMMENT ON TABLE core.erp_migration_marker IS 'Marcadores de adopción ERP para documentar hitos de migración V1 -> V2.';

CREATE TABLE IF NOT EXISTS core.legacy_objeto_mapeo (
    legacy_mapeo_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    origen_tabla VARCHAR(80) NOT NULL,
