-- Tabla: caja_operativa
CREATE TABLE caja_operativa (
    caja_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sucursal_codigo VARCHAR(40) NOT NULL DEFAULT 'MATRIZ',
    codigo VARCHAR(40) NOT NULL UNIQUE,
    nombre VARCHAR(120) NOT NULL,
    tipo_caja VARCHAR(30) NOT NULL DEFAULT 'VENTA' CHECK (tipo_caja IN ('VENTA','CAJA_CHICA','EVENTO','DELIVERY','OTRA')),
    moneda VARCHAR(3) NOT NULL DEFAULT 'USD',
    saldo_actual NUMERIC(12,2) NOT NULL DEFAULT 0,
    activa BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT ck_caja_operativa_saldo_no_negativo CHECK (saldo_actual >= 0)
);

-- Tabla: turno_caja
CREATE TABLE turno_caja (
    turno_caja_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    caja_id BIGINT NOT NULL REFERENCES caja_operativa(caja_id),
    usuario_apertura_id BIGINT NOT NULL REFERENCES usuario_sistema(usuario_id),
    usuario_cierre_id BIGINT REFERENCES usuario_sistema(usuario_id),
    fecha_apertura TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    fecha_cierre TIMESTAMPTZ,
    monto_apertura NUMERIC(12,2) NOT NULL DEFAULT 0,
    monto_cierre_sistema NUMERIC(12,2),
    monto_cierre_declarado NUMERIC(12,2),
    diferencia_cierre NUMERIC(12,2),
    estado VARCHAR(20) NOT NULL CHECK (estado IN ('ABIERTO','CERRADO','ANULADO')),
    observaciones_apertura VARCHAR(500),
    observaciones_cierre VARCHAR(500),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT ck_turno_caja_monto_apertura_no_negativo CHECK (monto_apertura >= 0)
);

CREATE UNIQUE INDEX ux_turno_caja_unico_abierto
    ON turno_caja (caja_id)
    WHERE estado = 'ABIERTO';

-- Tabla: movimiento_caja
CREATE TABLE movimiento_caja (
    movimiento_caja_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    turno_caja_id BIGINT NOT NULL REFERENCES turno_caja(turno_caja_id),
    tipo_movimiento VARCHAR(40) NOT NULL CHECK (tipo_movimiento IN ('APERTURA','VENTA_CONTADO','COBRO_CLIENTE','INGRESO_MANUAL','PAGO_PROVEEDOR','GASTO_CAJA','RETIRO_DEPOSITO','SALIDA_MANUAL','DIFERENCIA_ARQUEO','ANULACION')),
    naturaleza VARCHAR(20) NOT NULL CHECK (naturaleza IN ('ENTRADA','SALIDA','AJUSTE')),
    fecha_movimiento TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    monto NUMERIC(12,2) NOT NULL,
    moneda VARCHAR(3) NOT NULL DEFAULT 'USD',
    referencia_tipo VARCHAR(80),
    referencia_id VARCHAR(120),
    descripcion VARCHAR(500),
    estado VARCHAR(20) NOT NULL DEFAULT 'REGISTRADO' CHECK (estado IN ('REGISTRADO','ANULADO')),
    creado_por_usuario_id BIGINT NOT NULL REFERENCES usuario_sistema(usuario_id),
    anulado_por_usuario_id BIGINT REFERENCES usuario_sistema(usuario_id),
    anulado_en TIMESTAMPTZ,
    motivo_anulacion VARCHAR(500),
    CONSTRAINT ck_movimiento_caja_monto_positivo CHECK (monto > 0)
);

CREATE INDEX idx_movimiento_caja_turno_fecha ON movimiento_caja (turno_caja_id, fecha_movimiento DESC);
CREATE INDEX idx_movimiento_caja_referencia ON movimiento_caja (referencia_tipo, referencia_id);

