-- Tabla: rol_usuario
CREATE TABLE rol_usuario (
    rol_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    activo BOOLEAN NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    codigo VARCHAR(40) NOT NULL UNIQUE CHECK (codigo IN ('ADMIN','ATENCION','PRODUCCION')),
    nombre_rol VARCHAR(80) NOT NULL UNIQUE,
    descripcion VARCHAR(255)
);

-- Tabla: usuario_sistema
CREATE TABLE usuario_sistema (
    usuario_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    rol_id BIGINT NOT NULL REFERENCES rol_usuario(rol_id),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
